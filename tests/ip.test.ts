import { describe, expect, it } from "vitest";
import { isPublicIp } from "@/lib/scanner/ip";

describe("isPublicIp", () => {
  it.each([
    "0.0.0.0",
    "10.1.2.3",
    "100.64.0.1",
    "127.0.0.1",
    "127.255.255.254",
    "169.254.169.254",
    "172.16.0.1",
    "172.31.255.255",
    "192.0.2.1",
    "192.168.1.1",
    "198.18.0.1",
    "224.0.0.1",
    "255.255.255.255",
    "::",
    "::1",
    "::ffff:127.0.0.1",
    "::ffff:10.0.0.1",
    "::ffff:7f00:1",
    "fc00::1",
    "fd12:3456::1",
    "fe80::1",
    "fe80::1%en0",
    "ff02::1",
    "64:ff9b::a00:1",
    "2001:db8::1",
    "2002:7f00:1::1",
    "not-an-ip",
  ])("blocks %s", (ip) => {
    expect(isPublicIp(ip)).toBe(false);
  });

  it.each([
    "1.1.1.1",
    "8.8.8.8",
    "140.82.112.3",
    "172.32.0.1",
    "::ffff:8.8.8.8",
    "2606:4700:4700::1111",
    "2a00:1450:4001::200e",
  ])("allows %s", (ip) => {
    expect(isPublicIp(ip)).toBe(true);
  });
});
